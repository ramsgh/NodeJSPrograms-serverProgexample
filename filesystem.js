const fs = require('node:fs');

const fileName = 'example.txt';
const content = 'This text was generated by a Node.js program!';

// Write a file asynchronously
fs.writeFile(fileName, content, (err) => {
    if (err) {
        return console.error(`Error writing file: ${err.message}`);
    }
    console.log(`Successfully wrote data to ${fileName}`);
 
    // Read the file content back
    fs.readFile(fileName, 'utf8', (err, data) => {
        if (err) {
            return console.error(`Error reading file: ${err.message}`);
        }
        console.log(`File Content: "${data}"`);
    });
});
